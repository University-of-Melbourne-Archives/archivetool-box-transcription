package au.edu.unimelb.archivetool.app.cli.helpers

import com.github.ajalt.clikt.parameters.arguments.argument
import com.github.ajalt.clikt.parameters.arguments.default
import com.github.ajalt.clikt.parameters.types.path
import kotlin.io.path.Path

// Reusable job-directory argument for commands that use an existing job.
fun Command.jobDirectory() =
    argument("Job Directory", "A directory generated by this tool.")
        .path(
            // The job directory must already exist.
            mustExist = true,

            // It must be a directory, not a file.
            canBeFile = false,

            // The program must be able to read it.
            mustBeReadable = true,

            // Use the current directory if no job directory is supplied.
        )
        .default(Path("."), defaultForHelp = "current working directory")
